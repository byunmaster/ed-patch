"""**타이틀을 넘어가는 문안 사전의 키** — JP 원문 → sha1 앞 16자.

    from text.line_key import key
    key("%cライアス%c\n왕자…")   # PS1 의 `{c}ライアス{c}{n}…` 과 같은 키가 나온다

## 왜 공용인가

같은 팔콤 원문을 **여러 이식판이 나눠 갖는다**(PS1 · 세가새턴 · …). 사전
(`games/ps1-ed1+2/line_dict.json`)은 「타이틀을 넘어가는 유일한 창구」인데, 키가 **덤퍼의
표기를 타면** 같은 원문이 판마다 다른 키가 된다:

    PS1     `{c}ライアス{c}{n}なんだよ これ !?`
    새턴    `%cライアス%c\nなんだよ これ !?`      ← 같은 원문, 다른 키

🔴 실측(2026-08-20, PS1): 중립화 전 새턴 15,468 문자열 중 붙는 게 **1.3%**, 중립화 후
   **71.9%**. 2026-08-27 재측정으로 **84.2%**(ED1SCN 95.6% · ED2SCN 96.0%).
   **사전이 있어도 못 쓰고 있었던 셈이다.**

⚠ 규칙이 두 곳에 있으면 조용히 갈라진다 — 그래서 여기가 정본이다.
  (둘째 소비자가 실재해서 올렸다: PS1 이 만들고 **새턴이 읽는다** — 루트 CLAUDE.md YAGNI)

## 무엇을 중립화하나

- **마크업** — 창·색 전환(`{c}`/`%c`), 개행(`{n}`/진짜 개행), 인자(`%s`·`%d`).
  ⚠ 인자는 **자리만 표시**하고 값은 안 담는다 — 플랫폼마다 자리가 달라 그대로는 못 붙인다.
- **공백 전부** — 이식판은 줄나눔이 다르다.
- **가운뎃점 세 꼴**(`･`·`・`·`｡`) — 덤퍼마다 다르게 적는다.
- `\x21` — 이식판이 `!` 를 문자로 쓰는 자리가 있다.
"""

import hashlib
import re

# 덤퍼마다 표기가 다르다 — PS1 은 `{c}`·`{n}`, 새턴은 `%c`·진짜 개행.
_NEUTRAL = [
    ("{c}", "\x01"),
    ("%c", "\x01"),  # 창·색 전환
    ("{n}", ""),  # 개행 — 어차피 공백과 함께 지운다
    ("\\x25\\x73", "\x02"),
    ("%s", "\x02"),  # 이름 인자
    ("\\x25\\x64", "\x03"),
    ("%d", "\x03"),  # 수치 인자
    ("\\x21", "!"),  # 이식판이 문자로 쓰는 자리가 있다
]
_DOTS = str.maketrans({"･": "·", "・": "·", "｡": "。"})
_WS = re.compile(r"\s+")


def neutral(jp: str) -> str:
    """플랫폼 중립꼴 — 키를 만들기 직전의 모습. 디버깅용으로 따로 뺐다."""
    s = jp
    for a, b in _NEUTRAL:
        s = s.replace(a, b)
    return _WS.sub("", s.translate(_DOTS))


def key(jp: str) -> str:
    """JP 원문 → sha1 앞 16자. ⚠ **평문이 아니다** — 원문을 커밋에 안 남기려는 것이다."""
    return hashlib.sha1(neutral(jp).encode("utf-8")).hexdigest()[:16]
