#!/bin/sh
# sfc-ed2 커밋 전 게이트 — scripts/check.sh 가 부른다.
#
# ⚠ 아직 빌드·번역이 없다(기계 작업 라운드 — 조사 단계). 지킬 수 있는 것만 본다:
#   원본 지문·내부 헤더 · 글꼴 표 추출 · 대본 후보 스캐너 재현. 게이트는 지금 고칠 수 있는 것만 실패로 친다.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
PY="$ROOT/.venv/bin/python"
[ -x "$PY" ] || PY=python3
T="$ROOT/games/sfc-ed2/tools"

echo "== sfc-ed2 =="

# 1. 원본 지문 + 내부 헤더(HiROM) + 체크섬 합
"$PY" "$T/common.py"

# 2. 글꼴 — 12×12 전각 글리프 색인 $9C 가 읽히는가(좌표·배열이 틀리면 형태가 깨진다)
"$PY" "$T/font.py" 0x9c >/dev/null

# 3. 대본 후보 스캐너 — 덩이 수가 흔들리면(코드 규칙·상한 변경) 운다
"$PY" "$T/scan_text.py" | head -1 | grep -q "덩이 2335개 · 글자 137,975"

# 4. 대사 문법 — 메시지 단위 수·글자 수가 흔들리면(토큰 규칙 변경) 운다. 문법 밖에서 끊긴 덩이는 17(UI·코드 섞인 자리)
"$PY" "$T/script.py" | grep -q "메시지 단위 3,141개 · 전각 글자 137,035 · 문법 밖에서 끊긴 덩이 17"
"$PY" "$T/segs.py" | grep -q "글자 구간 4,051개"

# 5. 빌드 — textmap 번역을 얹은 2MB 롬: 코드 패치 단언 · 무변경 구간 대조 · 헤더 체크섬 · 결정성(두 번 빌드 sha1 대조). 일본어·글리프 모자람은 실패(2026-10-12 부터 --strict 가 기본, 시험용은 --lenient)
"$PY" "$T/build.py" --twice | grep -q "sha1="

# 5a. 구조 대조 + 재배치 장부 — 원본·빌드의 모든 대사 구간에서 엔진이 밟는 제어 코드 열을 맞대고(어긋나면 다음 블록 호출이 막혀 대사가 빠진다 — ss-ed3 10-21), 빌드가 뽑은 장부(relocations.tsv)와 롬에서 따라간 재배치가 같은지·장부 밖 쓰기가 없는지 본다
"$PY" "$T/check_structure.py" | grep -q "어긋남 0 "

# 5b. 번역 규칙 2-11 — 「…」 뒤에 말이 이어지면 공백
"$PY" "$T/check_ellipsis.py" | grep -q "위반 0"

# 5c. 번역 규칙 항목별 정적 검사(1-1·1-3·1-7·2-1~2-5·2-11·2-12·3-5 + 조판 결과) — 「안 잰」 항목은 출력 끝에 적힌다
"$PY" "$T/check_rules.py" | grep -q "규칙 위반 0"

# 5d. 정본 고유명사 × 조사(이/가·은/는·과/와·을/를) 받침 대조 — 우리 문안 전량(기존 검사가 못 보는 축)
"$PY" "$T/check_josa_nouns.py" | grep -q "받침 불일치 0"

# 6. 글리프표 — 1,284자 길이 불변식(한 글자라도 빠지면 이후 색인이 전부 밀린다)
"$PY" "$T/glyphmap.py" | grep -q "글리프표 1284자"

