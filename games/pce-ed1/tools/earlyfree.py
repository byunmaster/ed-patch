"""지역이 바뀌는 씬 전환 — 옛 씬 컨테이너를 **지역 묶음을 올리기 전에** 내린다(11-22 마스터 「세이브파일 1,3번 왔다갔다 하다보면 … 전투프리징」).

🔴 원인(실측 — `$5595` 할당 실패 출구에서 잡았다): 씬 진입 루틴(뱅크 0x6A `$65EA~`)은 지역(`$C1B6`)이 바뀌면
  ① 옛 지역 묶음 둘을 내리고(`$9274`) ② **새 지역 묶음 둘을 올린 뒤**(`$921F` — A → `$3A0A`, B → `$3A0B`) ③ 그제야 옛 씬 컨테이너를 내리고 새것을 올린다(`$6B8C`).
  ②의 순간에 캐시에는 상주 6뱅크 + **옛 컨테이너** + 새 묶음 A + B 가 같이 있다. 4장 솔디스(지역 3)는 묶음이 2 + 3 = 5뱅크라, 옛 컨테이너가 4뱅크면
  6 + 4 + 5 = 15 — 원판 16칸에는 들어가고 한글판 14칸(글리프 뱅크 둘이 슬롯 14·15)에는 안 들어간다. 묶음 B 가 **조용히** 안 올라오고(로더의 캐리를 아무도 안 본다)
  `$3A0B` 가 빈 그룹을 가리킨 채 남아, 그 지역의 전투가 쓰레기 그림을 그리다 멈춘다. 새로 켜서 4장 세이브를 바로 읽으면 옛 컨테이너가 없어 멀쩡하다 —
  「3장 세이브(요르도, 컨테이너 4뱅크) → 게임 안 LOAD 로 4장 세이브」에서만 난다.

고침: ②의 먼 호출(`JSR $4FD8 / 04 1F 92`, 뱅크 0x6A +0x60B, 6B)을 이 스텁의 먼 호출로 바꾼다(이 자리는 **장이 바뀔 때만** 지나간다 — `$65FB` 의 `CMP $6B`). 스텁은
  · 옛 컨테이너 그룹(`$61`)을 지금 내린다(`$5597` — `$374A` bit0 을 세워 조각 모으기도 돌 수 있다).
  · 🔴 그 그룹 번호를 **슬롯 14 를 가리키게** 해 둔다(`$378D[$61] = 0x0E`). 번호가 빈 채(0x80)면 새 묶음이 그 번호를 받아 가고, 뒤따르는 `$6B8C` 의
    `LDA $61 / JMP $5597` 이 **방금 올린 묶음을 내려 버린다.** 슬롯 14 는 글리프 뱅크 자리라 주인표(`$374C+14`)가 늘 0 이고 할당·조각 모으기가 `CPX #$0E` 로
    거기까지 안 간다 — 그래서 뒤의 내림은 아무것도 안 건드리고 번호만 돌려준다.
  · 원래 먼 호출(묶음 올리기)을 그대로 한다.
  · 🔴 **필드로 가는 전환**(11-23 — `$6B8C` 가 컨테이너를 안 바꾸는 조건: `$C009 != 3` 이고 `$C00F + $C010 == 0`)이면 여기서 **(새 장, 지역 0) 컨테이너를 올린다**
    (엔진의 `$6BAB` 를 먼 호출 — 맡겨 둔 번호를 돌려받고 `$6BAE` 로 적재, 새로 켜서 필드 세이브를 읽는 길 `$664C` 과 같은 컨테이너). 그리고 `$6C`(컨테이너 지역 기억)를
    0xFF 로 해 둔다 — 다음 마을 진입 때 컨테이너·지역 자료가 반드시 다시 올라온다(`$6C` 는 `$6B8C`·`$6C7E` 의 비교에만 쓰인다 — 전 뱅크 스캔).
    왜: 원판은 필드로 갈 때 컨테이너를 그대로 둔다. 장이 바뀌는 필드행(3장 마을 → 게임 안 LOAD 로 4장 필드 세이브)이면 **옛 장의 컨테이너**가 남는다 —
    실측(11-23): 해적섬(4뱅크) → 4장 필드 = 상주 6 + 옛 컨테이너 4 + 묶음 A 2 + B 3 = 15 > 14, 묶음 B 가 안 올라오고(필드는 겉보기 멀쩡 · 디버그를 열면 검은 창으로 멈춤).
    11-22 판은 「안 바꾸는 전환은 손대지 않는다」로 이 길을 건너뛰었다. 게다가 원판 그대로면 `$6B` 만 새 장이 되고 `$6C` 는 옛 지역이라, 새 장에서 **같은 지역 번호**의
    마을에 들어가면 `$6B8C` 가 「같다」고 보고 옛 장 컨테이너를 그대로 쓴다(원판의 잠재 결함) — 그것도 같이 없어진다.
    ⇒ 불변식: **올라와 있는 씬 컨테이너는 늘 지금 장 참조표의 것**(`check_cache_pieces` 의 장별 한도가 이 위에 선다).
전환 순간 점유가 상주 6 + 새 묶음(≤5)으로 줄어 어느 장에서 어느 장으로 가든 들어간다. 정상 상태 점유는 상주 6 + 묶음 + 그 장의 컨테이너 조각(게이트가 ≤ 14 로 잰다).

자리: 뱅크 0x70 `+0x194F`(임시 적재 빌리기 `transient_fallback` 끝 뒤 ~ 잘린 그림 사본 토막 a `+0x1980` 앞, 49B). 먼 호출 인자 08 = 뱅크 0x70 을 MPR3(`$6000`)에.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hook

BANK = 0x70
OFF = 0x194F
ROOM = 0x31  # ~ +0x1980(`sprmask` 토막 a)
ORG = 0x6000 + OFF
SITE_BANK = 0x6A
SITE_OFF = 0x060B  # 논리 `$660B`
FAR = b"\x20\xd8\x4f"  # `JSR $4FD8` + 뱅크(기준 0x68) · 주소 lo · hi
SITE_OLD = FAR + b"\x04\x1f\x92"  # 묶음 올리기(뱅크 0x6C/0x6D `$921F`)
RELOAD = FAR + b"\x02\xab\x6b"  # 엔진의 컨테이너 바꾸기(뱅크 0x6A `$6BAB` — `$61` 내리고 (`$C1B6`, `$C010`) 컨테이너 올림)
FREE_GROUP = 0x5597
GROUP_SLOT = 0x378D  # 그룹 → 슬롯(0x80 = 빈 번호)
PARK_SLOT = 0x0E  # 글리프 뱅크 자리(슬롯 14) — 주인표가 늘 0
AREA_MEMO = 0x6C  # 올라와 있는 컨테이너의 지역 번호(`$6B8C`·`$6C7E` 가 `$C010` 과 비교)


def site_new() -> bytes:
    return FAR + bytes([BANK - 0x68]) + ORG.to_bytes(2, "little")


def code() -> bytes:
    a = hook.Asm(ORG)
    a.op("LDY", "zp", 0x61)  # 옛 컨테이너 그룹 — 엔진(`$6BE3`)처럼 번호 범위는 안 본다
    a.op("LDA", "absy", GROUP_SLOT)
    a.op("BMI", "rel", "bundle")  # 올라와 있지 않다
    a.op("TYA")
    a.op("JSR", "abs", FREE_GROUP)  # Y = 그룹 번호 그대로 돌아온다
    a.op("LDA", "imm", PARK_SLOT)
    a.op("STA", "absy", GROUP_SLOT)
    a.label("bundle")
    a.data(SITE_OLD)
    a.op("LDA", "abs", 0xC009)  # `$6B8C` 의 조건 그대로 — 장은 이미 달라졌으니 남는 건 이 둘
    a.op("CMP", "imm", 3)
    a.op("BEQ", "rel", "done")  # 컨테이너를 바꾸는 전환 — 뒤의 `$6B8C` 가 올린다
    a.op("LDA", "abs", 0xC00F)
    a.op("CLC")
    a.op("ADC", "abs", 0xC010)
    a.op("BNE", "rel", "done")
    a.data(RELOAD)  # 필드행 — (새 장, 지역 0) 컨테이너
    a.op("LDA", "imm", 0xFF)
    a.op("STA", "zp", AREA_MEMO)
    a.label("done")
    a.op("RTS")
    b = a.bytes()
    assert len(b) <= ROOM, len(b)
    return b


if __name__ == "__main__":
    b = code()
    print(len(b), "B /", ROOM, "B · ORG", hex(ORG), "· 사이트", site_new().hex())
    print(b.hex())
