step "씬 대사" "$T/patch_scn.py" --apply
echo "  ── ED2 몬스터 이름 (제자리 우선 · 넘치면 칸끼리 재배치)"
step "몬스터 이름" "$T/patch_mon_names.py" --apply
echo "  ── 회심/통한 복사 루프 (14B 고정 → NUL 종단)"
step "회심 복사" "$T/patch_crit_copy.py" --apply
echo "  ── 전투 문구 복사 길이 (원문 일본어 바이트로 박힌 상수 → 우리 문안 길이)"
step "복사 길이" "$T/patch_msgcopy.py" --apply
echo "  ── ED2 몬스터 이름 고정 폭 복사 (언롤 → NUL 종단 루프)"
step "이름 복사" "$T/patch_namecopy.py" --apply
# 🔴 **메시지 창은 그리기 전에 prewrap 이 줄을 나눈다**(2026-09-27). 원 루틴은 일본어용 글자
#    단위라 `레스`/`1` 이 갈리고 줄머리에 공백·마침표가 왔다 — 어절 단위로 갈아 끼운다.
#    병기는 그 앞에서 조사 훅의 `접기` 진입점이 접는다(아래 「조사 훅」). 규칙 정본 `msgwrap.py`.
echo "  ── 메시지 창 줄 나누기 (prewrap → 어절 단위)"
step "줄 나누기" "$T/patch_msgwrap.py" --apply
echo "  ── 고정 길이 복사 전수 (칸에 맞나 · 빌드 이미지 기준)"
step "고정 복사" "$T/check_fixed_copy.py"
echo "  ── 포인터 정렬 (두 바이트 고정으로 읽는 화면이 있다)"
step "포인터 정렬" "$T/check_ptr_align.py"
# 🔴 **세이브가 우리 글리프 코드를 그대로 담는다** — 파티원 이름이 백업 RAM 에 우리 한글
#    슬롯 코드로 적힌다(실측 2026-09-06: 유저 세이브 32KB 안 16곳). 슬롯이 하나라도
#    움직이면 **옛 세이브의 이름이 깨진다.** pce-ed1 이 실제로 물린 사고다.
echo "  ── 글리프 배정 (덧붙이기만 했나 — 세이브 호환)"
step "글리프 배정" "$T/check_glyph_map.py"
echo "  ── 정본 (같은 원문이 두 표기로 갈렸나)"
step "정본" "$T/check_glossary.py"
