step "산문 사전" "$T/check_prose_glossary.py"
# 🔴 **자기 표 0**(마스터 2026-10-08 「모든 워커는 자기사전을 들고 있으면 안 돼」) — 게임 폴더에 JP→KR 표(가나·한자
#    열쇠)가 남으면 실패. 값은 전부 `shared/canon` 에서 읽는다. 예외는 스크립트 머리말(승인 기록 · 스태프롤).
echo "  ── 자기 표 0 (게임 폴더에 JP→KR 표가 없나)"
step "자기 표" "$T/check_own_tables.py"
# 🔴 **PS1 대조는 게이트여야 한다**(2026-09-06 점검에서 빠진 걸 찾았다). 「PS1 저본,
#    원문 우선」이 이 트랙의 문안 방침인데, 검사기가 손으로만 돌아 **언제든 조용히 갈릴 수
#    있었다.** ⚠ PS1 워크트리가 없으면 스스로 「⏭ 건너뜀」 하므로 늘 빨간불이 되지 않는다.
# 🔴 **무변경 구간** — 우리가 안 여는 파일·오디오·시스템 영역이 그대로인가(2026-09-06).
#    PS1 은 `build.py:IMMUTABLE` 로 오프셋 구간을 선언하는데, 새턴은 **파일 단위 재삽입**이라
#    「재삽입기가 여는 파일의 여집합」으로 선언한다. LBA 는 재배치로 바뀌므로 판정은
#    **파일 내용의 sha1** 이다.
# 🔴 **라운드트립은 되읽기와 다른 것을 묻는다**(2026-09-06). 되읽기는 「내가 쓴 것이
#    그대로 있나」고, 이건 「**덤프 → 재조립이 원본과 같나**」다 — 둘째가 없으면 **덤퍼가
#    잃는 것**을 영영 못 본다(덤퍼가 못 읽은 자리는 검사 대상에 들지도 않는다).
# 🔴 **이주한 뒤 옛 자리를 보는 참조가 있나 · 남의 인자를 덮었나**(pc98 중계 2026-09-07).
#    거기선 **분기 옵코드의 주소 바이트**가 텍스트 런 머리로 딸려 들어가, 문안을 쓰자
