#    머리는 게임 자신이 증명하지만, **덤프가 못 찾은 참조**가 옛 자리를 볼 수는 있다.
#    ⚠ 라운드트립은 이 축을 **안 본다**(덤프가 원본과 같은지만 본다).
# 🔴 **앞 단계가 깔아 둔 것을 뒤 단계가 덮었나**(2026-09-07 — 유저 인게임 캡처에서 왔다).
#    되읽기는 「내가 쓴 것이 그대로 있나」를 **자기가 쓴 직후에** 묻고, 라운드트립은 덤프↔원본,
#    무변경 구간은 **안 여는 파일**을 본다 — 셋 다 이 축을 안 본다. 실제로 `patch_scn` 의
#    이주 풀이 `patch_ui` 가 깔아 둔 이름 표 32칸을 덮었고, 화면에 「c의 공격」·「陸를
#    얻었다」가 떴는데 **게이트는 전부 초록이었다.**
echo "  ── 고유명사 표 (체인이 끝난 이미지에서 포인터를 따라가 되읽는다)"
step "이름 표" "$T/check_name_tables.py"
