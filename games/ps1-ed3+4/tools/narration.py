def _apply_overrides(m, txt, f, y0):
    """`GLYPH_OVERRIDES` 에 있는 글자의 칸을 통째로 덮어 그린다.

    x 는 그 글자 **앞까지의 누적 폭**(advance)으로 찾는다 — 이 폰트는 한글 16px·
    아스키/숫자/부호 8px 로 글자마다 폭이 다르니 `문자 순번×16` 으로 계산하면 안 된다.
    """
    d = ImageDraw.Draw(Image.new("L", (8, 8)))
    for i, ch in enumerate(txt):
        rows = GLYPH_OVERRIDES.get(ch)
        if rows is None:
            continue
        x0 = round(d.textlength(txt[:i], font=f))
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                m[y0 + ry, x0 + rx] = c == "#"
    return m


def _hires_truth(ch, scale=12):
    """neodgm 을 192px(16×12)로 그려 12배 LANCZOS 다운샘플 — 힌팅 왜곡이 거의 없는
    **참값**. 16px 렌더는 트루타입 힌팅이 2px 세로획을 3px 로, 1px 가로획을 2줄로
    뭉개는데, 이 왜곡은 렌더 크기와 무관하게 대개 1~2px 고정폭이라 192px 에서는
    상대적으로 무시할 수준이 된다(2026-09-18 검증: 이 방식으로 뽑은 11자가 관리자가
    독립적으로 192px 로 뽑은 것과 픽셀까지 일치, 마스터가 도트판에서 확인·승인).
    """
    big = ImageFont.truetype(NEODGM, 16 * scale)
    img = Image.new("L", (20 * scale, 48 * scale), 0)
    ImageDraw.Draw(img).text((0, 8 * scale), ch, font=big, fill=255)
    small = img.resize((20, 48), Image.LANCZOS)
    return np.asarray(small) > 100


def _lowres_raw(ch):
    f = ImageFont.truetype(NEODGM, 16)
    img = Image.new("L", (20, 48), 0)
    ImageDraw.Draw(img).text((0, 8), ch, font=f, fill=255)
    return np.asarray(img) > 100


def _diff_score(ch):
    """저해상도 실제 렌더와 참값의 픽셀 차이 — 0 이면 결함 없음(2026-09-17 밤
    검증: 마스터 손도안 21종 중 20종이 이 방식으로 정확히 0점, 예외 1건은 받침 ㅅ
    대각선 끝이라 원래 들쭉날쭉한 게 정상인 자리)."""
    return int((_lowres_raw(ch) ^ _hires_truth(ch)).sum())


