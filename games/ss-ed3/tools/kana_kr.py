# 종성 인덱스 (0없음 1ㄱ 4ㄴ 8ㄹ 16ㅁ 19ㅅ 21ㅇ)
_JONG = {"ン": 4, "ッ": 19}

# 🔴 **받침 축약** — 한국식 외래어 표기의 핵심이다. 자음 + `u`/`o` 음절은 앞 글자의
#    받침으로 붙는 쪽이 표준에 가깝다: `ボルト`=**볼트** · `アルフ`=**알프** ·
#    `ラグピック`=**라그픽** · `デュルゼル`=**듀르젤**. 이걸 모르면 「보루토·아루후」가
#    나와 정발 코퍼스에서 한 건도 안 걸린다(실측: 자동 판정률 24% → 이 규칙으로 회복).
#    갈래가 많아 **후보로만 낸다** — 고르는 건 코퍼스다.
JONG_ALT = {
    "ル": 8,
    "ン": 4,
    "ム": 16,
    "ク": 1,
    "グ": 1,
    "ッ": 1,
    "ス": 19,
    "ツ": 19,
}
# 촉음은 **없는 셈 치는** 표기도 흔하다 — `ラグピック` = 라그**픽**(뒤 `ク` 가 받침이 된다).
DROPPABLE = ("ッ", "ー")


def _with_jong(syl, jong):
    """앞 음절에 종성을 붙인다. 이미 종성이 있으면 그대로 둔다."""
    if not ("가" <= syl <= "힣"):
        return None
    code = ord(syl) - 0xAC00
    if code % 28:
        return None
    return chr(0xAC00 + code + jong)


def candidates(kana, limit=96):
    """가타카나 → 한글 후보 목록(중복 없음, 많아야 `limit` 개)."""
    parts = []  # 각 자리의 후보들
    i = 0
    while i < len(kana):
        two = kana[i : i + 2]
        if two in DIGRAPH:
            v = DIGRAPH[two]
            parts.append(list(v) if isinstance(v, tuple) else [v])
            i += 2
            continue
        c = kana[i]
        if c == "ー":  # 장음 — 무시하는 표기가 표준이다
            parts.append([""])
            i += 1
            continue
        if c == "ッ":
            parts.append([("JONG", 1), ("JONG", 19), ""])  # ㄱ · ㅅ · 무시
            i += 1
            continue
        opts = []
        if c in BASE:
            v = BASE[c]
            opts += list(v) if isinstance(v, tuple) else [v]
        if c in _JONG:
            opts.append(("JONG", _JONG[c]))
        if c in JONG_ALT and ("JONG", JONG_ALT[c]) not in opts:
            opts.append(("JONG", JONG_ALT[c]))
        if opts:
            parts.append(opts)
            i += 1
            continue
        parts.append([c])  # 한자·기호는 그대로 (뒤에서 걸러진다)
        i += 1

    out = []
    for combo in itertools.product(*parts):
        buf = []
        ok = True
        for piece in combo:
            if isinstance(piece, tuple) and piece[0] == "JONG":
                if not buf:
                    ok = False
                    break
                merged = _with_jong(buf[-1], piece[1])
                if merged is None:  # 종성이 이미 찼으면 홀로 둔다
                    buf.append("ㄴ" if piece[1] == 4 else "")
                else:
                    buf[-1] = merged
            else:
                buf.append(piece)
        if ok:
            out.append("".join(buf))
        if len(out) >= limit * 6:
            break
    seen = []
    for s in out:
        if s and s not in seen:
            seen.append(s)
    return seen[:limit]
