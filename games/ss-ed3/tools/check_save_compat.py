"""세이브 호환 — **글리프 배정이 흔들리면 옛 세이브의 이름이 깨진다.**

    python3 games/ss-ed3/tools/check_save_compat.py

🔴 **세이브에 우리 한글 코드가 그대로 적힌다**(2026-09-06 실측, pce-ed1 발 제보로 확인).
   유저 백업 RAM 을 우리 배정표로 디코드하니 파티 이름과 지명이 그대로 읽혔다 —
   `쥬리오`·`크리스`·`라그픽 마을`(한 세이브에 27 자리). 즉 배정이 한 칸이라도 밀리면
   **옛 세이브를 새 빌드로 열 때 이름이 딴 글자로 뜬다.** 인게임 QA 중엔 바로 보이는 사고다.

⚠ **「우리 코드가 적혔나」를 바이트만 훑어 판정하면 오탐한다**(ps1-ed1+2 제보 — 세이브 제목의
   `伝説` 이 그쪽 표에도 있어 한글로 읽혔다). 그래서 **쓰는 쪽으로 확인했다**:
   ① 우리 칸은 원판이 쓰는 글리프와 **하나도 안 겹친다**(10/10 검사) ·
   ② **원판(일본어) 세이브의 같은 오프셋**에 `ジュリオ`(0xda3)·`ラグピック村`(0x188b)이 있다.
   같은 자리에 원판은 일본어를, 우리 것은 한글을 적는다 — 이름 칸이 맞다.

✅ 다행히 이 게임의 배정은 **문안과 무관**하다 — 완성형 2,350 자를 통째로, 가나다순으로
   빈 슬롯에 앉힌다(`hangul_map.assign`). 그래서 **문안을 고쳐도 안 흔들린다.**
🔴 흔들리는 건 하나뿐이다 — **`used_indices()`(원본에서 「쓰는 글리프」를 훑는 것)가 바뀌고
   그 상태로 `--freeze` 를 다시 돌리는 것.** 소재를 하나 더 열면 빈 슬롯 목록이 통째로 밀린다.
   ⇒ 이 검사기는 **정본과 지금 소재가 갈렸는지**를 알린다. 갈린 것 자체는 실패가 아니다
   (빌드는 정본만 읽는다) — 다만 그 상태에서 `--freeze` 를 돌리면 **옛 세이브와 옛 빌드가
   통째로 깨진다**는 것을 여기서 못 박아 둔다.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import font as F
import hangul_map as H


def main():
    table = H.load()
    fresh = H.assign(F.free_slots(F.used_indices()))
    same = table == fresh
    print(f"   배정 {len(table):,}자 · 세이브에 이 코드가 적힌다(파티 이름·지명)")
    if same:
        print("   ✅ 정본이 지금 소재와 같다 — 다시 얼려도 자리가 안 바뀐다")
        return 0
    moved = sum(1 for ch, i in table.items() if fresh.get(ch) != i)
    print(f"   ⚠ 정본과 지금 소재가 갈렸다 — 다시 얼리면 {moved:,}자가 딴 칸으로 간다")
    print("     빌드는 정본만 읽으니 지금 이미지는 멀쩡하다. 🔴 다만 `--freeze` 를 돌리면")
    print("     **옛 세이브의 이름이 깨지고 옛 빌드의 문안이 전부 딴 글자가 된다.**")
    print("     소재를 새로 열었더라도 배정은 그대로 두는 것이 맞다(자리는 남아 있다).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
