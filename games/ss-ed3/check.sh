#!/bin/sh
# 이 게임의 커밋 전 게이트 — [kr] 새턴 『백의 마녀』.
#
#   sh games/ss-ed3/check.sh      (보통은 `sh scripts/check.sh` 가 부른다)
#
# ⚠ 아직 **이미지를 굽지 않는다**(정적 분석 단계). 그래서 「빌드가 되나」가 아니라
#   **「원본을 읽는 전제가 그대로인가」**가 1급 검사다. 재삽입이 서면 여기에 빌드가 붙는다.
#
# 🔴 이 게임의 뿌리 전제는 **2디스크 계약**이다 — 「양쪽에 있는 파일은 바이트 동일,
#    갈리는 건 매체뿐」. 이게 깨지면 「문안을 한 벌만 만든다」는 설계가 통째로 무너진다.
set -eu

G=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$G/../.." && pwd)
PY="$ROOT/.venv/bin/python"
[ -x "$PY" ] || PY=python3

fail=0

# 🔴 **파이프는 종료 코드를 먹는다.** `cmd | sed || fail=1` 은 **sed 의** 결과를 보므로
#    검사기가 1 로 죽어도 `fail` 이 안 선다 — 이 게이트는 그렇게 **한동안 아무 것도 못
#    잡고 있었다**(2026-08-29 실측: `check_build_discs` 가 🔴 를 찍었는데 「통과」가 떴다).
#    POSIX sh 엔 `pipefail` 이 없으니, **출력을 먼저 받고** 종료 코드를 따로 본다.
#    ⚠ 값을 정하는 자리라 `|| rc=$?` 로 닫는다(루트 CLAUDE.md 「셸」).
#    `run`   = 실패하면 게이트가 죽는다 · `warn` = 찍기만 한다 · 인자 `-N` 은 tail.
#    ⚠ 변수 이름에 `_` 를 붙인다 — **POSIX sh 엔 지역 변수가 없어** 함수가 부르는 쪽의
#      이름을 덮는다. 처음엔 `n` 을 썼다가 `for n in 1 2` 루프를 갈아엎어 `--disc 0` 이
#      됐다(2026-08-29 실측 — 고친 게이트가 그 자리에서 이걸 잡아냈다).
_run() {
  _gate=$1; _tail=$2; shift 2
  _out=$("$@" 2>&1) && _rc=0 || _rc=$?
  if [ "$_tail" -gt 0 ]; then printf '%s\n' "$_out" | tail -"$_tail" | sed 's/^/   /'
  else printf '%s\n' "$_out" | sed 's/^/   /'; fi
  [ "$_rc" -eq 0 ] || [ "$_gate" = warn ] || fail=1
}
run()  { _run gate "$@"; }
warn() { _run warn "$@"; }

# 원본이 없는 트리(다른 워크트리·CI)에서는 **건너뛴다.** 늘 빨간불인 게이트는 아무도 안 본다.
if [ ! -d "$ROOT/originals/jp/ss-ed3" ]; then
  echo "  ⏭ originals/jp/ss-ed3 가 없다 — 원본이 필요한 검사는 건너뛴다"
  exit 0
fi

echo "  ── 원본 지문 · 2디스크 계약"
run 0 "$PY" "$G/tools/common.py"

# ⚠ 게이트다 — 락도 관측 대장도 조판을 안 본다(화자+본문만 해시). 공용(`shared/text/josa`)
#   이 조사 배정을 흔들면 여기서만 운다(루트 CLAUDE.md 「조판은 락도 관측 대장도 안 본다」).
# 🔴 **`tail` 로 자르지 않는다** — 이 검사의 첫 줄이 통과/실패 헤드라인이라, 자르면
#   실패해도 헤드라인 없이 상세 줄만 보여 사람이 놓친다(ss-ed1+2 `check.sh` 실측 함정).
echo "  ── 조판 지문 (공용이 조사·화면 문안을 흔들었나)"
warn 0 "$PY" "$ROOT/scripts/check/typeset_fingerprint.py" --game ss-ed3

# 🔴 **덤프 라운드트립** — 경계가 한 칸이라도 밀리면 재삽입이 옆 바이트를 먹는다.
#    두 디스크 다 본다(같은 한 벌이라는 계약을 텍스트 층에서도 다시 확인하는 셈이다).
echo "  ── 번역이 그 블록의 것인가 (원문 지문)"
run 0 "$PY" "$G/tools/stamp_script.py" --check

echo "  ── 말투 (한 블록 안에서 높임과 반말이 섞였나)"
# ⚠ 경고지 실패가 아니다 — 한 블록 안에서 말 상대가 바뀌는 자리가 실제로 있다
warn 3 "$PY" "$G/tools/check_speech.py"

echo "  ── 화자 이름이 본문에서 또 나가나 (F4 이름창 메아리)"
# 🔴 게이트다 — 이름창이 제 줄에 이름을 찍는데 번역이 본문에 이름표 꼴을 옮겨 쓰면 화면에 이름이 두 번 나간다
run 0 "$PY" "$G/tools/check_name_echo.py"

echo "  ── 메뉴 라벨이 칸을 넘치나 (F5 창 프레임)"
# 🔴 게이트다 — 바이트가 맞아도 반각이 섞이면 폭이 다르다. 받아들인 넘침은 script/window_frame_accept.json
run 0 "$PY" "$G/tools/check_window_frame.py"

echo "  ── 이름표가 자리마다 다르게 옮겨졌나"
# 🔴 게이트다 — 라벨은 판단이 들어갈 자리가 없다(같은 사람이 두 이름으로 보인다)
run 12 "$PY" "$G/tools/check_label.py"

echo "  ── 고유명사 뒤 조사가 받침과 맞나"
# 🔴 게이트다 — **표기를 바꾸면 조사가 안 따라온다**(「라우아르가」→「라우알가」)
run 10 "$PY" "$G/tools/check_josa.py"

echo "  ── 숫자에 붙는 단위 표기 (붙여쓰기)"
# 🔴 게이트다 — 판단이 안 든다. 규칙이 하나뿐이고(`숫자+단위`는 붙임) `--apply` 가 고친다.
#    원문이 근거가 못 되는 자리라(일본어엔 띄어쓰기가 없다) **우리 문안의 다수결**로 정했는데,
#    그런 규칙은 적어 두기만 하면 반드시 샌다 — 실제로 47:2 로 갈려 있었다(2026-09-01).
run 9 "$PY" "$G/tools/check_units.py"

echo "  ── 부호가 홀로 다음 줄로 밀리나 (조판)"
# 🔴 게이트다 — **정본 키가 조용히 안 붙는 자리**를 잡는다. 「원문은 파일에 있는데
#    종결 바이트(`\x10`·`\x0f`)가 안 맞아」 못 찾으면, 그 문자열을 **품고 있던 짧은 키**가
#    뒷부분만 먹어 앞머리가 일본어로 남는다 — 빌드도 게이트도 초록인 채로
#    화면에 「経験値２０と / 7 고아를 얻었다!」가 떴다(유저 실측 2026-08-31).
#    그날 이 검사기를 붙이자 **같은 사고 넷**(레벨업·기술습득·보물상자·미지원)이 더 나왔다.
echo "  ── 시스템 문안이 전부 붙나 (종결 바이트)"
run 8 "$PY" "$G/tools/reinsert_sys.py"

# 🔴 게이트다 — 위 검사와 **축이 다르다.** `reinsert_sys` 는 「표에 있는 것이 다 들어갔나」를
#    세는데, **표에 아예 없는 원문**은 실패도 종결 불일치도 아니라 조용히 화면에 나간다.
#    실측(유저 인게임 QA 2026-09-07): 승리 문구가 조각 셋인데 마지막만 표에 있어
#    화면에 「쥬리오は、전투에 이겼다!」가 떴다. 빌드도 게이트도 초록이었다.
echo "  ── 표에 없는 일본어가 남았나 (시스템 문자열 커버리지)"
run 6 "$PY" "$G/tools/check_sys_coverage.py" --check

# 🔴 게이트다 — 판단이 안 든다. 고치는 법이 정해져 있고(`--apply`) **길이도 안 변한다**.
#    엔진은 어절을 안 보고 17 슬롯에서 글자 단위로 접는다(유저 실측 2026-08-30).
run 6 "$PY" "$G/tools/fix_orphans.py" --check

# 🔴 게이트다 — 판단이 안 든다. **일본어 `、` 가 개행 앞에 남아 있던 자리 3,479** 를 뺐는데
#    (2026-09-06), 새 문안을 쓰면 다시 들어온다. 한국어는 개행 앞에 쉼표를 안 찍는다.
#    ⚠ 뒤가 빈 줄뿐인 쉼표는 「다음 창으로 이어진다」는 표시라 검사기가 봐준다.
run 4 "$PY" "$G/tools/fix_line_commas.py" --check

# 🔴 게이트다 — 판단이 안 든다. 검은 바탕 가운데 정렬 화면(나레이션·장 카드)은 원문 앞 공백을
#    그대로 옮겨 **줄마다 가운데가 달랐다**(마스터 폰 실측 2026-09-26, 엔딩 나레이션).
#    실제 렌더 폭(전각 1 · 반각 0.5)으로 다시 잡는다 — 고치는 법은 인자 없이 돌리면 된다.
run 4 "$PY" "$G/tools/center_narration.py" --check

# 🔴 게이트다 — 조판 여섯 규칙(①고아·폭 ②빈 줄 ③첫 칸 공백 ④묶음 끊김) 전 영역 전수.
#    걸린 것 중 설계(원판 여백·조각)·이월(대사 라운드)은 사유를 적어 대장에 두고,
#    **대장 밖에서 새로 생기면 실패**한다. ⑤⑥ 은 위 char_cols·reinsert_desc·check_josa 가 본다.
echo "  ── 조판 여섯 규칙 (전 영역 · 대장 밖 새 위반)"
run 2 "$PY" "$G/tools/check_typeset6.py" --check

echo "  ── 원문에 있던 것이 사라지지 않았나 (숫자 · 고유명사)"
warn 3 "$PY" "$G/tools/check_fidelity.py"

echo "  ── 덤프 라운드트립 (대사 · 시스템 · 두 디스크)"
for n in 1 2; do
  run 0 "$PY" "$G/tools/dump_map.py" --disc "$n" --check
  run 0 "$PY" "$G/tools/dump_sys.py" --disc "$n" --check
done

# 🔴 **구워 둔 이미지가 지금 소스의 것인가 · 두 장이 같은 세대인가.**
#    `build.py` 는 두 장을 차례로 굽는다 — 굽는 **도중에** 소스를 고치면 앞장만 낡는데
#    빌드는 성공하고 게이트도 초록이었다(유저 실측 2026-08-28: disc2 만 한 판 뒤처졌다).
#    ⚠ 이미지가 없으면 건너뛴다 — 안 구운 트리에서 늘 빨간불이면 아무도 안 본다.
# 🔴 **세이브에 우리 한글 코드가 적힌다** — 배정이 밀리면 옛 세이브의 이름이 깨진다.
#    실패로 치지 않는다(빌드는 정본만 읽는다). `--freeze` 를 돌리려는 사람에게 알리는 자리다.
echo "  ── 세이브 호환 (글리프 배정이 흔들리지 않나)"
warn 0 "$PY" "$G/tools/check_save_compat.py"

echo "  ── 구워 둔 이미지가 지금 소스의 것인가 (두 장 대조)"
run 0 "$PY" "$G/tools/check_build_discs.py"

# 🔴 게이트다 — **글 소실 없음** 불변식. 위 검사기들은 「넣으려던 문안」을 보고, 이건
#    「이미지에 들어간 것」을 되풀어 본다(공백·개행 제외 글자열이 script/ 와 같은가).
#    ps1-ed3+4 가 대사 꼬리를 폭 한도로 잘라 버리는데 검사기가 0 건이던 사고(09-27)의 짝.
#    ⚠ 1 분쯤 걸린다(두 장 전량 되읽기). 이미지가 없으면 스스로 건너뛴다.
echo "  ── 글 소실 없음 (구운 이미지를 되풀어 문안과 대조)"
run 3 "$PY" "$G/tools/check_no_loss.py"

if [ "$fail" -ne 0 ]; then
  echo "  ❌ [ss-ed3] 게이트 실패"
  exit 1
fi
echo "  ✅ [ss-ed3] 통과"
