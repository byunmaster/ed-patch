"""sfc-ed1 대사창 가변 폭(VWF) — 공백·`. , ? !` 를 **반 칸(4px)** 으로 그린다(마스터 Q5, 2026-10-08).

배경: 대사창은 8px 타일 칸 17×4 배열이고 엔진이 글자마다 칸 번호를 하나 올린다. 반 칸 전진이면 칸 경계에 걸친 글자마다
(앞 글자 오른쪽 4px + 뒤 글자 왼쪽 4px) 타일이 따로 필요한데 미리 구우면 수천 종이다(devlog 10-08) — 그래서 **런타임에 합성**한다.

설계(훅 `hook`/`hookbuf` 가 글자를 내줄 때 한 곳에서):
  · 훅이 **px 커서 `V_VX`** 를 든다. 글자는 폭 `w`(8 또는 반각류 4)와 8×16 1bpp 그림(`V_G`)을 가진다.
  · **8px 글자가 칸 시작(off=0)에 오면 예전 길 그대로**(`alloc` — 글리프 캐시·슬롯 재사용) → 반각이 없는 줄은 바이트까지 같다.
  · 그 밖(반각이 칸을 시작하거나, off=4 위치)은 **합성 칸**: 슬롯 하나를 새로 받고 슬롯별 WRAM 버퍼(`BUF` + 슬롯×16B)에
    글자를 시프트해 OR 한 뒤 NMI 큐로 올린다(큐 항목 `Q_HI=$FF` = RAM 원본, `Q_LO` = 슬롯).
  · 새 칸이 생기지 않는 반각(off=4 에 4px)은 **엔진에 글자를 안 돌려주고 삼킨다** — 엔진은 칸 하나당 글자 하나만 센다.
  · 엔진 칸 번호(`$173B`)와 px 커서가 어긋나면(개행·페이지·창 지움·줄 올림) 칸 번호를 믿고 커서를 다시 맞춘다(`vwf_sync`).
버퍼 `$7E:E100~` 는 필드 이동·대사·메뉴에서 쓰기 0건을 쓰기 BP 로 확인한 구역이다(2026-10-08, status).
"""

BUF = 0x7EE100  # 슬롯별 합성 버퍼 — 16B(1bpp, 위 타일 8행 + 아래 타일 8행) × 슬롯
HALF_CODES = (0x10, 0x83, 0x84, 0x0C, 0x0F)  # 공백 · `.` · `,` · `!` · `?`
# 같은 몬스터가 여럿일 때 엔진이 이름 뒤에 붙이는 A~D(`$02:E0CE` 표) — 마스터 10-09 「ABCD 도 반각」: 우리 글꼴 4px 합성으로
LETTER_CODES = (0xC3, 0xC4, 0x8F, 0x8E)


def emit(a, k):
    """`a` = Asm, `k` = 훅이 쓰는 주소·라벨 이름 모음(dict). 호출 규약: A 8비트 · X/Y 16비트(훅 본체와 같다)."""
    V_VX, V_VS, V_VD, V_VW, V_VO = k["V_VX"], k["V_VS"], k["V_VD"], k["V_VW"], k["V_VO"]
    V_SH = k["V_SH"]
    V_VCELL, V_VT, V_VNC, V_VR, V_VCODE, V_VRSLOT, V_G = (
        k["V_VCELL"],
        k["V_VT"],
        k["V_VNC"],
        k["V_VR"],
        k["V_VCODE"],
        k["V_VRSLOT"],
        k["V_G"],
    )
    V_T0, V_T1, V_NEXT, V_HEAD = k["V_T0"], k["V_T1"], k["V_NEXT"], k["V_HEAD"]
    V_CTX, V_OVERFLOW, V_IDX = k["V_CTX"], k["V_OVERFLOW"], k["V_IDX"]
    V_OPEN, V_OCELL, V_NLF = k["V_OPEN"], k["V_OCELL"], k["V_NLF"]
    V_WM = k["V_WM"]
    V_CUR, V_MXD, V_SCR = k["V_CUR"], k["V_MXD"], k["V_SCR"]
    V_PALD, V_PT, V_WK = k["V_PALD"], k["V_PT"], k["V_WK"]
    owner_lo, owner_hi, pin = k["owner_lo"], k["owner_hi"], k["pin"]
    Q_SLOT, Q_LO, Q_HI, Q_CTX = k["Q_SLOT"], k["Q_LO"], k["Q_HI"], k["Q_CTX"]
    nslot, QN, GLYPH_BASE = k["nslot"], k["QN"], k["GLYPH_BASE"]
    G16 = V_G & 0xFFFF  # 뱅크 $7E 안의 16비트 주소 — DBR=$7E 로 바꿔 abs,Y 로 읽는다
    WOFF = nslot * 16  # 흰 잉크 마스크 버퍼(`BUF + WOFF`) — 슬롯 버퍼 뒤에 같은 모양으로 둔다

    def lm(op, addr):
        a.op(op, addr=addr, mode="long")

    # ── 칸 번호와 px 커서 맞추기 ────────────────────────────────────────────────
    # 나갈 때: V_VT = 엔진이 **다음에 쓸 칸** · V_VCELL = 커서가 가리키는 칸 · V_VO = 칸 안 위치(0 | 4)
    a.label("vwf_sync")
    a.phx()
    a.sep(imm=0x20)
    lm("lda", V_OPEN)  # 크롤(오프닝·엔딩)은 자기 칸 카운터, 대사 엔진은 `$173B`
    a.beq(label="vsy_d")
    lm("lda", V_OCELL)
    a.bra(label="vsy_c")
    a.label("vsy_d")
    lm("lda", 0x00173B)
    a.label("vsy_c")
    a.inc()
    lm("sta", V_VT)
    a.rep(imm=0x20)
    lm("lda", V_VX)
    a.lsr()
    a.lsr()
    a.lsr()
    a.sep(imm=0x20)
    lm("sta", V_VCELL)
    lm("lda", V_VX)
    a.op("and", imm=0x07)
    lm("sta", V_VO)
    a.beq(label="vsy_al")
    lm("lda", V_VT)  # 칸 안 중간이면 그 칸이 엔진의 「마지막으로 쓴 칸」이어야 한다
    a.dec()
    lm("cmp", V_VCELL)
    a.beq(label="vsy_ok")
    a.bra(label="vsy_reset")
    a.label("vsy_al")
    lm("lda", V_VT)
    lm("cmp", V_VCELL)
    a.beq(label="vsy_ok")
    a.label("vsy_reset")
    a.rep(imm=0x20)
    lm("lda", V_VT)
    a.op("and", imm=0x00FF, m16=True)
    a.asl()
    a.asl()
    a.asl()
    lm("sta", V_VX)
    a.sep(imm=0x20)
    lm("lda", V_VT)
    lm("sta", V_VCELL)
    a.lda(imm=0x00)
    lm("sta", V_VO)
    a.label("vsy_ok")
    a.plx()
    a.rts()

    # ── 합성 칸용 슬롯 하나 (캐시를 안 쓴다 — 오너를 $FFFF 로) → A = 슬롯 번호 ───────────
    # ── 슬롯이 화면에 살아 있나 (X = 슬롯, 16비트) → C=1 이면 창 칸 배열(`$0305`, 17×4)이 그 슬롯의 코드를 쓴다 ──
    # 🔴 라운드로빈은 「가장 오래 할당된 슬롯」을 내주는데, 합성 칸은 칸마다 슬롯 하나를 새로 먹어(캐시 불가) 전투 로그처럼
    #    길게 쌓이는 창에서는 **아직 화면에 있는 칸이 한 바퀴 돌아 덮였다**(2026-10-08 실측 — 로그 첫 줄 머리가 끝 글자로 바뀜).
    #    살아 있는 칸은 건너뛴다. 칸 배열은 68바이트라 한 번에 훑는다.
    a.label("vwf_live")
    a.op("lda", addr="slot_code", mode="absx")
    a.ldx(imm=0x0000, m16=True)
    a.label("vl_l")
    a.op("cmp", addr=0x000305, mode="longx")
    a.beq(label="vl_y")
    a.inx()
    a.cpx(imm=68, m16=True)
    a.bne(label="vl_l")
    a.clc()
    a.rts()
    a.label("vl_y")
    a.sec()
    a.rts()

    a.label("vwf_newslot")
    a.lda(imm=nslot)
    lm("sta", V_T0)
    a.label("vn_try")
    lm("lda", V_NEXT)
    a.cmp(imm=nslot)
    a.bcc(label="vn_t0")
    a.lda(imm=0x00)
    lm("sta", V_NEXT)
    a.label("vn_t0")
    a.rep(imm=0x20)
    a.op("and", imm=0x00FF, m16=True)
    a.tax()
    a.sep(imm=0x20)
    if k["xfrom"] < nslot:  # 크롤 전용 슬롯은 인게임에서 건너뛴다(`hook.alloc` 과 같은 규칙)
        a.cpx(imm=k["xfrom"], m16=True)
        a.bcc(label="vn_nx")
        lm("lda", V_CTX)
        a.cmp(imm=0x01)
        a.bne(label="vn_skip")
        a.label("vn_nx")
    a.op("lda", addr=pin, mode="longx")
    a.bne(label="vn_skip")
    a.jsr(addr="vwf_live", mode="abs")  # 지금 창 칸 배열이 쓰는 슬롯이면 건너뛴다
    a.bcc(label="vn_take")
    a.label("vn_skip")
    lm("lda", V_NEXT)
    a.inc()
    lm("sta", V_NEXT)
    lm("lda", V_T0)
    a.dec()
    lm("sta", V_T0)
    a.bne(label="vn_try")
    a.label("vn_take")
    lm("lda", V_NEXT)
    a.cmp(imm=nslot)
    a.bcc(label="vn0")
    a.lda(imm=0x00)
    a.label("vn0")
    lm("sta", V_T1)
    a.inc()
    a.cmp(imm=nslot)
    a.bcc(label="vn1")
    a.lda(imm=0x01)
    lm("sta", V_OVERFLOW)
    a.lda(imm=0x00)
    a.label("vn1")
    lm("sta", V_NEXT)
    lm("lda", V_T1)
    a.rep(imm=0x20)
    a.op("and", imm=0x00FF, m16=True)
    a.tax()
    a.sep(imm=0x20)
    a.lda(imm=0xFF)
    a.op("sta", addr=owner_lo, mode="longx")
    a.op("sta", addr=owner_hi, mode="longx")
    lm("lda", V_T1)
    a.rts()

    # ── 슬롯 버퍼 16B 를 0 으로 (A = 슬롯) ────────────────────────────────────────
    a.label("vwf_clrbuf")
    a.rep(imm=0x20)
    a.op("and", imm=0x00FF, m16=True)
    a.asl()
    a.asl()
    a.asl()
    a.asl()
    a.tax()
    a.sep(imm=0x20)
    a.lda(imm=0x00)
    a.ldy(imm=0x0010, m16=True)
    a.label("vc_l")
    a.op("sta", addr=BUF, mode="longx")
    a.op("sta", addr=BUF + WOFF, mode="longx")
    a.inx()
    a.dey()
    a.bne(label="vc_l")
    a.rts()

    # ── 글자 그림 → 슬롯 버퍼에 OR (V_VRSLOT = 슬롯, V_SH = 시프트 0~7) ─────────────────────────────
    # 가변 폭이라 글자가 칸 안 **어느 열에서나**(0~7) 시작한다 — 그림을 오른쪽으로 V_SH(현재 칸에 걸치는 몫) 또는
    # 왼쪽으로 V_SH(다음 칸으로 넘치는 몫, = 8 − 시작 열) 민다. 행 루프 안에서 횟수를 세면 레지스터가 모자라
    # 시프트 횟수마다 본체를 따로 둔다(`vbR0~7` · `vbL1~7`, 조립 때 만든다).
    for d, op, rng in (("R", "lsr", range(8)), ("L", "asl", range(1, 8))):
        a.label(f"vwf_blit{d}")
        lm("lda", V_SH)
        for n in rng:
            if n == 0:
                continue
            a.cmp(imm=n)
            a.bne(label=f"vd{d}{n}")
            a.jsr(addr=f"vb{d}{n}", mode="abs")
            a.bra(label=f"vx{d}")
            a.label(f"vd{d}{n}")
        if d == "R":
            a.jsr(addr="vbR0", mode="abs")  # V_SH = 0
        a.label(f"vx{d}")  # L 0 은 없다(넘칠 몫이 없다) — 그대로 나간다
        a.rts()
        for n in rng:
            name = f"vb{d}{n}"
            a.label(name)
            a.rep(imm=0x20)
            lm("lda", V_VRSLOT)
            a.op("and", imm=0x00FF, m16=True)
            a.asl()
            a.asl()
            a.asl()
            a.asl()
            a.clc()
            a.op("adc", imm=BUF & 0xFFFF, m16=True)
            a.tax()
            a.sep(imm=0x20)
            a.phb()
            a.lda(imm=0x7E)
            a.pha()
            a.plb()
            a.ldy(imm=0x0000, m16=True)
            a.label(name + "_l")
            a.op("lda", addr=G16, mode="absy")
            for _ in range(n):
                getattr(a, op)()
            a.op("sta", addr=V_SCR & 0xFFFF, mode="abs")
            a.op("ora", addr=0x0000, mode="absx")
            a.op("sta", addr=0x0000, mode="absx")
            a.op("lda", addr=V_CUR & 0xFFFF, mode="abs")  # 혼합 칸에 흰 글자가 얹히면 잉크를 흰 잉크 마스크에도(혼합 칸은 흰 잉크만 색인 1)
            a.bne(label=name + "_s")
            a.op("lda", addr=V_WK & 0xFFFF, mode="abs")
            a.beq(label=name + "_s")
            a.op("lda", addr=V_SCR & 0xFFFF, mode="abs")
            a.op("ora", addr=WOFF, mode="absx")
            a.op("sta", addr=WOFF, mode="absx")
            a.label(name + "_s")
            a.inx()
            a.iny()
            a.cpy(imm=0x0010, m16=True)
            a.bne(label=name + "_l")
            a.plb()
            a.rts()

    # ── 업로드 큐에 「RAM 원본 슬롯」 항목을 넣는다 (A = 슬롯) ─────────────────────────
    a.label("vwf_enq")
    a.phx()
    lm("sta", V_T1)  # 본체 임시 — 이 함수가 끝나면 필요 없다
    a.jsr(addr="q_wait", mode="abs")  # 큐가 가득이면 기다린다(`hook.q_wait`)
    lm("lda", V_HEAD)
    a.rep(imm=0x20)
    a.op("and", imm=0x00FF, m16=True)
    a.tax()
    a.sep(imm=0x20)
    lm("lda", V_T1)
    a.op("sta", addr=Q_SLOT, mode="longx")
    a.op("sta", addr=Q_LO, mode="longx")
    a.lda(imm=0xFF)  # 글리프 색인 상위로는 절대 안 나오는 값 = RAM 원본 표지
    a.op("sta", addr=Q_HI, mode="longx")
    lm("lda", V_CTX)
    a.op("sta", addr=Q_CTX, mode="longx")
    lm("lda", V_HEAD)
    a.inc()
    a.op("and", imm=QN - 1)
    lm("sta", V_HEAD)
    a.plx()
    a.rts()

    # ── 글자 그림 읽기 → V_G[16] ─────────────────────────────────────────────────
    # 한글(V_IDX = 글리프 색인): 글리프 뱅크 32B/자(평면0·평면1 번갈아) → 평면0 만 16행
    a.label("vwf_ldg_h")
    a.rep(imm=0x20)
    lm("lda", V_IDX)
    for _ in range(5):
        a.asl()
    a.tax()
    a.sep(imm=0x20)
    a.phb()
    a.lda(imm=0x7E)
    a.pha()
    a.plb()
    a.ldy(imm=0x0000, m16=True)
    a.label("lgh_l")
    a.op("lda", addr=GLYPH_BASE, mode="longx")
    a.op("sta", addr=G16, mode="absy")
    a.inx()
    a.inx()
    a.iny()
    a.cpy(imm=0x0010, m16=True)
    a.bne(label="lgh_l")
    a.plb()
    a.rts()
    # 원본 1바이트 글자(V_VR = 코드): 훅 뱅크의 `rawtab` 16B/자
    a.label("vwf_ldg_r")
    a.rep(imm=0x20)
    lm("lda", V_VR)
    a.op("and", imm=0x00FF, m16=True)
    a.asl()
    a.asl()
    a.asl()
    a.asl()
    a.tax()
    a.sep(imm=0x20)
    a.phb()
    a.lda(imm=0x7E)
    a.pha()
    a.plb()
    a.ldy(imm=0x0000, m16=True)
    a.label("lgr_l")
    a.op("lda", addr="rawtab", mode="longx")
    a.op("sta", addr=G16, mode="absy")
    a.inx()
    a.iny()
    a.cpy(imm=0x0010, m16=True)
    a.bne(label="lgr_l")
    a.plb()
    a.rts()

    # 인게임 숫자(원판 시트 꼴, 왼쪽으로 한 칸 붙인 것): 훅 뱅크의 `numtab` 16B/자
    a.label("vwf_ldg_n")
    a.rep(imm=0x20)
    lm("lda", V_VR)
    a.op("and", imm=0x00FF, m16=True)
    a.asl()
    a.asl()
    a.asl()
    a.asl()
    a.tax()
    a.sep(imm=0x20)
    a.phb()
    a.lda(imm=0x7E)
    a.pha()
    a.plb()
    a.ldy(imm=0x0000, m16=True)
    a.label("lgn_l")
    a.op("lda", addr="numtab", mode="longx")
    a.op("sta", addr=G16, mode="absy")
    a.inx()
    a.iny()
    a.cpy(imm=0x0010, m16=True)
    a.bne(label="lgn_l")
    a.plb()
    a.rts()

    # 색이 바뀌는 자리 — 합성 칸이 반쯤 찬 상태면 칸 경계로 올린다(팔레트가 칸 단위라 한 칸에 두 색이 섞인다)
    a.label("vwf_csnap")
    a.phx()
    a.jsr(addr="vwf_sync", mode="abs")
    lm("lda", V_VO)
    a.beq(label="cs_done")
    a.rep(imm=0x20)
    lm("lda", V_VX)
    a.clc()
    a.op("adc", imm=7, m16=True)
    a.op("and", imm=0xFFF8, m16=True)
    lm("sta", V_VX)
    a.lsr()
    a.lsr()
    a.lsr()
    a.sep(imm=0x20)
    lm("sta", V_VCELL)
    a.label("cs_done")
    a.plx()
    a.rts()

    # 색 끝($E1) — 혼합 팔레트 칸(`vwf_cellmix`)이 한 칸에 두 색을 섞으므로 칸 경계로 올릴 일이 없다
    a.label("vwf_cend")
    a.rts()

    # 색 시작 토큰(X = $E2|$E3|$DC) — 칸 안 중간에서 색이 바뀌어도 대개 혼합 칸으로 풀린다(`vwf_cellmix`). 칸이 이미 **다른 색 둘을 섞은**
    # 경우(이름 바로 뒤 다른 색 — 드물다)만 예전처럼 칸 경계로 올린다.
    a.label("vwf_cstart")
    a.phx()
    a.phy()
    a.jsr(addr="vwf_sync", mode="abs")
    lm("lda", V_VO)
    a.beq(label="cst_end")
    a.cpx(imm=0x00E2, m16=True)
    a.bne(label="cst_n2")
    a.lda(imm=0x04)
    a.bra(label="cst_c")
    a.label("cst_n2")
    a.lda(imm=0x0C)
    a.label("cst_c")
    lm("sta", V_SCR)  # 새 색
    lm("lda", V_VCELL)
    a.rep(imm=0x20)
    a.op("and", imm=0x00FF, m16=True)
    a.tax()
    a.sep(imm=0x20)
    a.op("lda", addr=0x000349, mode="longx")  # 지금 칸의 색
    a.beq(label="cst_end")
    lm("cmp", V_SCR)
    a.beq(label="cst_end")
    a.cmp(imm=0x14)
    a.bne(label="cst_m2")
    lm("lda", V_SCR)
    a.cmp(imm=0x0C)
    a.beq(label="cst_end")
