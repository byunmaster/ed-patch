#!/bin/sh
# sfc-ed1 커밋 전 게이트 — scripts/check.sh 가 부른다.
#
# ⚠ 아직 빌드가 없다(쓰기 경로를 안 만들었다 — patcher-checklist 2). 지금 지킬 수 있는 건
#   **입력 지문 · 포인터 표/사전 스캔의 재현 · 문자표 불변식**이라 그 셋을 본다.
#   게이트는 **지금 고칠 수 있는 것**만 실패로 친다(루트 CLAUDE.md).
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
PY="$ROOT/.venv/bin/python"
[ -x "$PY" ] || PY=python3
T="$ROOT/games/sfc-ed1/tools"

echo "== sfc-ed1 =="

# 1. 원본 지문 + 내부 헤더 — 소장본이 바뀌거나 손댄 롬이면 여기서 죽는다
"$PY" "$T/common.py"

# 조판 지문(F10) — 번역 문안 전량을 조판기(typeset.wrap→layout)에 태운 구역별 해시. 조판 규칙·후보·글꼴 폭이
# 바뀌면 운다. 문안을 의도적으로 바꿨을 때만 `--freeze`(자동 갱신 금지). 값은 games/sfc-ed1/typeset_fingerprint.json.
"$PY" "$ROOT/scripts/check/typeset_fingerprint.py" --game sfc-ed1

# 2. 대본 — 포인터 표 4벌(3339·433·343·19) · 사전 6벌 · main 글자 177,108B. 스캐너가 흔들리면 운다
"$PY" "$T/text.py" --check

# 3. 스크립트 라벨 모델 — 본체 153KB 를 라벨로 풀어 오프셋을 다시 계산해 되쓰면 바이트가 같아야 한다
"$PY" "$T/script.py" --roundtrip

# 4. 배치기 — 확장 뱅크로 옮겨 쓴 롬을 되읽어 원본 디코드와 대조 + 무변경 구간 byte 대조(파일은 안 남긴다)
"$PY" "$T/build.py" --check

# 5. 번역 정본 — textmap 의 번역문이 조각의 토큰(사전·제어)을 전부 같은 순서로 품는가(원문 덤프를 먼저 낸다)
"$PY" "$T/units.py" --dump >/dev/null
"$PY" "$T/textmap.py" --check

# 6. 한글 롬 경로 — **굴리는 이미지가 이 경로로 나온다.** 5번까지는 원문 배치만 보므로
#    번역을 끼운 뒤에야 생기는 사고를 못 잡는다(2026-09-08 저장 소프트락: 조각을 다시 담다가
#    `<E0>` 뒤의 `<E4>` 가 이웃과 떨어져 저장 문안이 옆 문안으로 흘러 들어갔다 —
#    되읽기·왕복·무변경 구간 셋 다 초록이었다). 파일은 안 남긴다(`--project`).
#    여기서 죽는 것: 흘러내림 이웃이 끊김 · 종료 꼴이 갈림 · 군집이 뱅크를 넘음 ·
#    무변경 구간 · 사전/전투 UI 되읽기.
"$PY" "$T/build.py" --project >/dev/null

# 7. 조판 — 필드 조립형 시스템 메시지(도구·주문·상태 결과)에 **실제 후보 전체**(인물·도구·주문+레벨·수·장소)를
#    넣어 17칸 창에 흘려 본다. 엔진은 17칸째에서 기계적으로 넘기므로 넘친 자리가 줄 첫 칸 부호·공백·어절 끊김이 된다
#    (2026-09-27 — 「세리오스의 주문은 봉인되어 있다」+「!」 가 딱 17칸이라 「!」 가 고아가 됐다).
#    🔴 필드·전투·씬 **전 영역**에서 tm-draft 아닌 위반이 하나라도 있으면 실패한다(종전엔 필드만 막아
#    전투·씬이 되돌아가도 초록이었다 — 2026-09-27 전 세션 점검, 전투 조각에 위반을 넣어 실패 확인).
"$PY" "$T/typeset.py" --check

# 8. 대사창 가변 폭(VWF, `hook_vwf.py`) — **정본은 켜진 채**(마스터 판정 10-08)라 위 1~7번이 켠 경로를 본다. 꺼진 경로(`ED_VWF=0`,
#    시험·대조용)도 같은 문안으로 조판 위반 없고 투영이 서는지 매번 본다 — 안 보면 꺼진 코드가 조용히 썩는다.
ED_VWF=0 "$PY" "$T/typeset.py" --check
ED_VWF=0 "$PY" "$T/build.py" --project >/dev/null

# 9. 조사 일치(F8) — 을/를 받침 불일치 · 런타임 변수 뒤 고정 조사. 0건 유지. 단위 테스트가 검사기 자신을 지킨다
"$PY" "$T/check_josa.py"

# 9b. 부호 규칙(번역 규칙 2-11 `…` 뒤 반각 공백 · 2-12 `?!` 앞에 `…` · 1-7 `～` 뒤 마침표 금지, 마스터 10-12) — 0건 유지
"$PY" "$T/check_punct.py"

# 10. 화면 일본어(F7) — 칸(사전·지명·메뉴)은 미번역 0 이어야 한다. 문장은 분모와 함께 알리기만(번역 중)
"$PY" "$T/check_jp_left.py"

# 11. 자기 표 0(마스터 10-08) — 게임 폴더에 JP→KR 표가 남았나. 정본에서 읽을 수 없는 값은 관리자 후보로 올리고 천장(own_tables_baseline.json)이 줄기만 한다
"$PY" "$T/check_own_tables.py"

# 12. 표 목표 — 메시지 포인터 표(main·alt1~3)의 목표가 번역 단위 목록(본체 구간) 안에 있나. 목록 밖 문장은 화면 일본어 게이트가 분모로도 못 본다
#     (2026-10-18: 메인 표 101개가 본체 밖 `$05`·`$1E` 를 가리켰는데 통째로 일본어였다). 기준선(textmap/targets_outside.json)보다 늘면 실패, 반입하면 줄인다
"$PY" "$T/check_targets.py"

# 13. 문장 끝 사전 토큰 덤프 · 글 뒤로 간 화자 이름표 — 토큰 계약(5번)은 「들어 있나」만 봐서 위치를 못 본다. `tm-draft` 가 토큰을 문장 끝에 덤프해
#     최종 롬에서 이름이 한 번 더 찍혔다(2026-10-18, 632조각). 기준선(textmap/tail_tokens_baseline.json)보다 늘면 실패
"$PY" "$T/check_tail_tokens.py"

# 14. 이름 뒤 조사 전수 — 정본 고유명사 전 목록(+사전이 푸는 이름) × 이/가·은/는·과/와·을/를 을 뒤 받침과 대조한다. 기존 조사 검사는 이 축을 많이 비켜 간다(md-ed2 「슬러그이」, 10-18)
"$PY" "$T/check_josa_names.py"

# 15. 제품 롬 실빌드 — 위 `--check`·`--project` 는 쓰기 직전까지만 간다(전투 UI 등 쓰기 경로 끝은 안 탄다). 정본 이름이 칸보다 길어도
#     rc 0 에 낡은 롬이 남던 구멍(md-ed2, 10-18). 낡은 롬·`.failed` 를 지우고 보고하는 그 제품 롬을 `--kr` 로 굽는다 — 실패·산출물 없음이면 실패
"$PY" "$T/check_real_build.py"

# 16. 번역 정본에 PUA(U+E000~F8FF) 0 — PS1 문안을 끌어올 때 딸려 오는 내부 자리표시 문자는 다른 기종 글리프로 구워진다(md-ed2 「약초구말이군」, 10-18)
"$PY" "$T/check_pua.py"

# 17. 토큰 자리 — 제어·사전 토큰이 원문과 같은 쪽(글 앞/뒤)에 있나. 토큰 계약(5번)은 순서만 봐서 PS1 문안 뒤에 토큰을 몰아 붙인 초안이 통과했다
#     (「물건이옵니다.감사합니다.」·「주지.세리오스」·소니아 대사 무한 되풀이, 2026-10-19 qa). 0건 유지
"$PY" "$T/check_token_order.py"
