#!/bin/sh
# md-ed1 커밋 전 게이트 — scripts/check.sh 가 부른다.
#
# 빌드는 tools/build.py(허용 구간 밖 쓰기 거부 · 무변경 대조 · 화면 바이트 게이트). 여기선 빌드 없이
#   **입력 지문 · 아카이브 분모 · 글꼴 형상 · 코덱 왕복 · 씬 모듈 분모 · 정본 게이트**를 본다.
#   게이트는 **지금 고칠 수 있는 것**만 실패로 친다(루트 CLAUDE.md).
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
PY="$ROOT/.venv/bin/python"
[ -x "$PY" ] || PY=python3
T="$ROOT/games/md-ed1/tools"

echo "== md-ed1 =="

# 1. 원본 지문 + 헤더 체크섬 + 꼬리 빈 공간 — 소장본이 바뀌면 여기서 죽는다
"$PY" "$T/common.py"

# 2. 아카이브 — 대본 225블록 663,896B · 전투 110블록. 색인·디코더가 흔들리면 운다
"$PY" "$T/archives.py" --check

# 3. 글꼴 — 리소스 6 · 14×14 두 면 · SJIS 1,459자
"$PY" "$T/font.py" --check

# 3b. 한글 코드 배정 — 커밋본과 대조(세이브 호환: 이미 있던 글자는 코드가 안 밀린다)
"$PY" "$T/hangul.py" --check

# 4. 씬 모듈 — 스트림 2,750(0A 도 끝) · 화자 태그 1,425/1,437 도달(나머지 12 는 참조 없는 죽은 문안) · 225블록 항등 재조립이 다시 파싱해 같다
"$PY" "$T/scene.py" --check

# 5. 시스템 메시지 — 참조 스트림 + 워드 표 0x73bc + 고정 스트림 + 묶음 안 참조 = 163 · 묶음 66
"$PY" "$T/sysmsg.py" --check

# 6. 오프닝 자막 · 엔딩 문안 — 워드 스크립트 표 10 · 고유 스트림 39, 영역 안에 있는지
"$PY" "$T/captions.py" --check

# 6b. 전투 아카이브 — 이름 269(기본 100) · 고유 스트림 281(lea 180 + 플래그 11 + 자료 A 슬롯 90)
"$PY" "$T/battle.py" --check

# 6b2. 조사 훅 — 빈 제어코드(EB·EC)가 그대로인지, 손인코딩이 디코드되는지
"$PY" "$T/josa.py"

# 6b2-2. 로그 줄넘김 가드 — 렌더러의 반각 줄바꿈 호출이 원본 그대로인가(글자 단위 + 고아 부호·첫 칸 공백만 막음, 2026-09-27 밤)
"$PY" "$T/wordwrap.py" --check

# 6b2-3. 필드 HUD 뒷말·방위 — 문안을 안 거치는 여덟 자리가 원본 그대로인가(마스터 지적 2026-09-27,
#        「엘아스타 암」·「엘아스타 할」 — 부근·입구·동서남북이 코드에 SJIS 로 직접 박혀 있다)
"$PY" "$T/field_hud.py" --check

# 6b2-4. 필드 입장 배너 지명 표 — 대본 블록 91, scene.py 문안 스트림 밖이라 collect_chars() 가
#        안 보던 자리(마스터 지시 2026-09-27 밤 — 빈 배너, devlog 참조). 앵커가 원본과 같은지만 본다
#        (내용 검산은 build.py 가 표 전체를 다시 써 보며 한다)
"$PY" "$T/field_names.py" --check

# 6b2-5. 숨은 텍스트 — scene.py/battle.py 스트림 범위 밖 SJIS 런, **보고 전용**(실패 아님).
#        1,502건(script 112·battle 5블록) 확인, 대사 라운드 몫 — docs/status.md 「다음 라운드」
"$PY" "$T/check_hidden_text.py"

# 6b3. 조사 일치 — 훅의 짝(<02><eb>·<0e><ec>) · 손으로 쓴 조사 · 남은 병기(P2 게이트)
"$PY" "$T/check_josa.py" --check

# 6b3-2. 조사 일치(정적) — 이름 바로 뒤에 손으로 쓴 조사가 받침과 맞는가(기반 F8)
"$PY" "$T/check_josa_agreement.py" --check

# 6b3-3. 이름창 ≠ 본문 메아리(기반 F4)
"$PY" "$T/check_name_echo.py" --check

# 6b4. 문안 품질 — 원문 잔존 · 부호 규칙 · PS1/용어집 표기 일치
#      ⚠ 문서엔 「게이트에 있다」고 적혀 있었는데 **실제로는 안 불렸다**(2026-09-06 점검에서 잡힘).
"$PY" "$T/check_text.py"

# 6b4-2. 조립형 메시지 조판 — 가장 긴 이름·도구·주문·숫자를 끼워 메시지 창 210px 로 돌린다(고아 부호·빈 줄·
#        줄 첫칸 공백·저절로 줄넘김·조사 병기). 2026-09-27 「…에게 레스1을 외웠다 / .」 고아 온점이 계기
"$PY" "$T/check_layout.py"

# 6b5. 토큰 경계 — 분기 인자를 글자로 먹지 않았나(pc98-ed1 이 물린 부류, 2026-09-07)
"$PY" "$T/check_refs.py" --check

# 6c. 코드 영역에 남은 일본어 — 참조로 못 찾는 자리(워드 표·꼬리말)가 늘면 운다
"$PY" "$T/jp_left.py" --check

# 7. 정본 게이트 — 빌드 없이 미수록 글자 · 조판 · 참조 · 표 폭 · 묶음 폭 · 자막 영역/12비트 오프셋
"$PY" "$T/build.py" --check

# 8. 조판 지문 — 게이트가 아니라 보고다(shared/text/krwrap 이 대사 조판을 조용히 흔들면 여기서 운다).
#    안 바꿨는데 뜨면 `shared/` 를 의심한다.
"$PY" "$ROOT/scripts/check/typeset_fingerprint.py" --game md-ed1 2>&1 | sed 's/^/  /'
