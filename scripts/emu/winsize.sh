# 창 크기 단계 넷 — **실행기 셋이 같은 눈금을 쓴다** (유저 요청 2026-09-07).
#
#     . "$HERE/winsize.sh";  winsize_wh 3   # → 1280x960
#
# ⚠ **왜 한 곳에 두나** — 같은 「2단계」가 실행기마다 다른 크기면 눈금이 아니라 그냥 숫자다.
#   mednafen 은 배율(2·3·4·5배)로, DOSBox-X·np2kai 는 창 화소로 받는데, **사람이 보는 크기는
#   같아야** 한다. mednafen 쪽 배율표는 `mednafen_video.py:SIZES` 에 있고 여기와 짝이다 —
#   한쪽을 고치면 다른 쪽도 고친다.
#
#   기준은 mednafen 의 PS1(320×240)이다: 2배=640×480 … 5배=1600×1200.
#   DOSBox-X·np2kai 는 그 화소를 그대로 창 크기로 쓴다(안쪽 해상도는 안 건드린다).
#
#     1 매우 작음  640x480      3 보통   1280x960
#     2 작음(기본) 960x720      4 큼     1600x1200
winsize_wh() {
  case "${1:-2}" in
    1) echo 640x480 ;;
    3) echo 1280x960 ;;
    4) echo 1600x1200 ;;
    *) echo 960x720 ;;    # 2 = 기본. 알 수 없는 값도 여기로 떨어뜨린다
  esac
}
